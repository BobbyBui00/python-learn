## 4 pillars in OOP
#  1/ Encapsulation -
# Binding of data and functions that manipulate that data. And we encapsulate it into a big object so that we keep everything in this box
# that users or codes or other machines can interact with and this data and functions are what we call attributes and methods

#   2/ Abstraction -
# Hiding of information or abstracting away information and giving access to only what's necessary. So whatever the user or the programmer or the machine is interest in,
# that's the only thing we give access to. Everything else we hide it
# introduce the private and public variable

#   3/ Inheritance -
# Allow new objects to take on the properties of existing objects. So you can inherit classes

#   4/ Polymorphism -
# The idea of polymorphism refers to a way in which object classes can share the same method name. But those method name can act differently based on what object calls them
